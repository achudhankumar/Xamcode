let fetchImpl = (...a) => global.fetch(...a);
function loadServer(env) {
  const cut = src.indexOf('const server = http.createServer');
  if (cut < 0) throw new Error('server bootstrap not found');
  /* Scratch __dirname per harness: the disk image cache lives under it, so
     one block's successful images cannot leak into the next block's
     failure assertions. */
  const scratch = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'xc-img-'));
  const box = {
    console: { log() {}, warn() {}, error() {} },
    process: { env: Object.assign({}, env), hasOwnProperty: Object.hasOwn },
    require, __dirname: scratch, __filename: path.join(scratch, 'server.js'),
    Buffer, URL, fetch: (...a) => fetchImpl(...a),
    setTimeout, clearTimeout, setInterval, clearInterval,
    AbortController, TextEncoder, Intl
  };
  box.globalThis = box;
  vm.createContext(box);
  vm.runInContext(
    src.slice(0, cut) +
    '\nglobalThis.__t={handleTopicImages,generateImage,imageProvider,jobs,createAnalyzeJob};',
    box, { filename: 'server.js' }
  );
  return box.__t;
}
